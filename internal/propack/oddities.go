// Hotkey oddity kinds: habits a pro shows in nearly every game that almost no other pro of their race shares.
const (
	OddityHallKey        = "hall_key"
	OddityWorkerKey      = "worker_key"
	OddityFewKeys        = "few_keys"
	OddityRebinds        = "rebinds"
	OddityFastPresses    = "fast_presses"
	OddityUnitKey        = "unit_key"
	OddityProdKey        = "prod_key"
	OddityOpening        = "opening"
	OddityShiftAdds      = "shift_adds"
	OddityHotkeyShare    = "hotkey_share"
	OddityDeselects      = "deselects"
	OddityTechBinds      = "tech_binds"
	OddityFewHallBinds   = "few_hall_binds"
	OddityFirstSupply    = "first_supply"
	OddityComsatKeys     = "comsat_keys"
	OddityRareUnit       = "rare_unit"
	OddityStandardLayout = "standard_layout"
)

// HotkeyOddity is one conspicuous hotkey habit. Value is the hotkey of a key habit, the minutes of a worker
// habit (whose Key is the hotkey), the number of keys of few_keys (whose Baseline is the fewest any other player
// of the race uses), a percentage for opening and shift_adds, and the per minute rate of a rate habit (whose
// Baseline is the race's median player).
type HotkeyOddity struct {
	Kind  string `json:"kind"`
	Value int    `json:"value"`
	Key   *int   `json:"key,omitempty"`
	// Unit is the unit type of a unit_key habit; NormKey is the key most other players of the race use
	// instead, for unit_key and prod_key habits, whose lines are about the key number only.
	Unit         string `json:"unit,omitempty"`
	NormKey      *int   `json:"norm_key,omitempty"`
	NormMajority bool   `json:"norm_majority,omitempty"`
	// FromMinute is when a rare_unit habit's unit first holds its key.
	FromMinute int `json:"from_minute,omitempty"`
	// Keys are the hotkeys of a comsat_keys habit.
	Keys []int `json:"keys,omitempty"`
	// Tenths marks Value and Baseline as tenths, for rates shown with one decimal.
	Tenths bool `json:"tenths,omitempty"`
	// Binds are an opening habit's first binds, in order; Value is then the share of games opened that way.
	Binds []HotkeyBind `json:"binds,omitempty"`
	// Tied marks a rank shared with another player.
	Tied bool `json:"tied,omitempty"`
	// Rank is a rate habit's place among the race's pros, 1 being the highest.
	Rank     int `json:"rank,omitempty"`
	Baseline int `json:"baseline,omitempty"`
	// SharedCount is how many other pros of the race share the habit; SharedWith names them when every one
	// of them clearly does.
	SharedCount int      `json:"shared_count,omitempty"`
	SharedWith  []string `json:"shared_with,omitempty"`
	Population  int      `json:"population"`
}

// HotkeyBind is one bind of an opening: a building's name, or empty for units.
type HotkeyBind struct {
	Key      int    `json:"key"`
	Building string `json:"building,omitempty"`
}

// OdditiesFile is data/hotkey_oddities.json, generated by scripts/hotkey-oddities from the same corpus as
// the pack. Pros are keyed by pro ID, then by race name.
type OdditiesFile struct {
	Source string                               `json:"source,omitempty"`
	Pros   map[string]map[string][]HotkeyOddity `json:"pros"`
	// Rates are each pro's median hotkey tempo, by pro ID then race name.
	Rates map[string]map[string]hotkeystream.Rates `json:"rates,omitempty"`
}

func attachOddities(pack *Pack) error {
	raw, err := dataFS.ReadFile("data/hotkey_oddities.json")
	if err != nil {
		return nil
	}
	var file OdditiesFile
	if err := json.Unmarshal(raw, &file); err != nil {
		return fmt.Errorf("propack: parsing hotkey oddities: %w", err)
	}
	for id, byRace := range file.Pros {
		if pro := pack.ByID(id); pro != nil {
			pro.HotkeyOddities = byRace
		}
	}
	for id, byRace := range file.Rates {
		if pro := pack.ByID(id); pro != nil {
			pro.HotkeyRates = byRace
		}
	}
	return nil
}

// OdditiesFor returns the pro's oddities for a race name, or nil.
func (p *Pro) OdditiesFor(race string) []HotkeyOddity {
	if p == nil {
		return nil
	}
	for r, o := range p.HotkeyOddities {
		if strings.EqualFold(r, race) {
			return o
		}
	}
	return nil
}
